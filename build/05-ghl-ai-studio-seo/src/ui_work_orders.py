def filename(key: str) -> str:
    return f"{UI_WORK_ORDER_PREFIX}-{key}.md"


def build(paths: Paths | None = None) -> list[Path]:
    paths = paths or default_paths()
    written = []
    for key, fn in ORDERS.items():
        written.append(emit(f"work_order:{key}", paths.ui_work_orders / filename(key), fn(paths),
                            STATUS.READY_FOR_HUMAN, paths, source="src/ui_work_orders.py"))
    return written


