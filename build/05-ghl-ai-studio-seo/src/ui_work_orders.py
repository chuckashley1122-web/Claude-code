def human_decisions(paths: Paths) -> str:
    cfg = json.loads(paths.build_config.read_text(encoding="utf-8"))
    facts = json.loads(paths.business_facts.read_text(encoding="utf-8"))["facts"]
    lines = ["# 005 HUMAN-DECISIONS (SPEC-05)", "",
             f"WARNING: {C.FROZEN_CAMPAIGN_NAME} is FROZEN — never edit, pause or duplicate it; STRIPE is "
             "connected to that ad account, so any budget change is a real financial action. This build does not "
             "touch it.", "",
             "**Why:** Every unknown value and approval gate in SPEC-05 needs a named human decision.", "",
             f"**Where:** config/build_config.json, config/business_facts.json and the GHL account ({C.GHL_AGENCY_URL}).",
             "", "**Steps:**", "",
             "1. Work through each table below; replace NEEDS_EVIDENCE only with a value that has an evidence link.",
             "2. Re-run `python tools/build_all.py` from the build root after each change.", "",
             "**Verify:** `python tools/secret_scan.py` and `python tools/compliance_scan.py` exit 0 after edits.", "",
             "**Blocked by:** human access to GHL, the registrar, Search Console and approved business material.", "",
             "## NEEDS_EVIDENCE values", "", "| Key | Where | Owner | Next action |", "|---|---|---|---|"]
    for key, value in cfg.items():
        if value == NE:
            lines.append(f"| {key} | config/build_config.json | {C.OWNER_NAME} | Supply verified value |")
    for f in facts:
        if not f["verified"]:
            lines.append(f"| {f['key']} | config/business_facts.json | {f['owner']} | {f['next_action']} |")
    for name in ("SERVICE_ALLOWLIST", "ALLOWED_SOURCE_ORIGINS", "RATE_LIMIT_CONFIG"):
        lines.append(f"| {name} | config/constants.py | {C.OWNER_NAME} | Supply verified value |")
    lines += ["", "## Open blockers", "", "| Item | Missing input | Next action |", "|---|---|---|"]
    lines += [f"| {k} | {v['missing_input']} | {v['next_action']} |" for k, v in sorted(blockers(paths).items())]
    lines += ["", "## Approval gates", "", "| Gate | Dollar amount | Current state |", "|---|---|---|",
              f"| Site publish | $0 | SITE_PUBLISH_APPROVED = {C.SITE_PUBLISH_APPROVED} |",
              f"| Domain purchase | USD {NE} (quote required) | DOMAIN_PURCHASE_APPROVED = {C.DOMAIN_PURCHASE_APPROVED} |",
              f"| Ad spend | $0 cap | AD_SPEND_CAP_USD = {C.AD_SPEND_CAP_USD} |",
              f"| Estimator enablement | $0 | ESTIMATOR_ENABLED = {C.ESTIMATOR_ENABLED} |"]
    for i in spend_items()["items"]:
        lines.append(f"| {i['service']} | USD {i['cost_usd']} | approval required, none given |")
    lines.append("")
    return "\n".join(lines)


