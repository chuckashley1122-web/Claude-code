def _order(title: str, why: str, where: str, steps: list[str], verify: list[str], blocked_by: list[str],
           preamble: str = "") -> str:
    lines = [f"# {title}", ""]
    if preamble:
        lines += [preamble, ""]
    lines += [f"**Why:** {why}", "", f"**Where:** {where}", "", "**Steps:**", ""]
    lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)]
    lines += ["", "**Verify:**", ""]
    lines += [f"- {v}" for v in verify]
    lines += ["", "**Blocked by:**", ""]
    lines += [f"- {b}" for b in blocked_by]
    lines += ["", "_Generated by build/05-ghl-ai-studio-seo/src/ui_work_orders.py. Nothing in this order has "
              "been done by the build; record results in config/decision_log.jsonl via a human edit._", ""]
    return "\n".join(lines)


